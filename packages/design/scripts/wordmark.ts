/**
 * Draws "OUTCOME VAULT" in Syncopate Bold as shapes, once, into src/wordmark.generated.ts,
 * so the logo never depends on a font being loaded. Run again only if the wordmark's text or font changes.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import opentype from 'opentype.js';

const TEXT = 'OUTCOME VAULT';
const require = createRequire(import.meta.url);
const fontFile = require.resolve('@fontsource/syncopate/files/syncopate-latin-700-normal.woff');
const buffer = await readFile(fontFile);
const font = opentype.parse(buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength));
const size = font.unitsPerEm;
const path = font.getPath(TEXT, 0, 0, size);
const capHeight = (font.tables.os2 as { sCapHeight?: number } | undefined)?.sCapHeight;
if (!capHeight) throw new Error('The font has no cap height.');

await writeFile(
  new URL('../src/wordmark.generated.ts', import.meta.url),
  `// Generated by scripts/wordmark.ts from Syncopate Bold. Do not edit.
/** "${TEXT}" as one path, in font units: baseline at y = 0, letters above it (negative y). */
export const wordmark = {
  text: ${JSON.stringify(TEXT)},
  unitsPerEm: ${size},
  capHeight: ${capHeight},
  width: ${Math.round(font.getAdvanceWidth(TEXT, size))},
  d: ${JSON.stringify(path.toPathData(1))},
} as const;
`,
);
console.log('Wordmark written to src/wordmark.generated.ts');
